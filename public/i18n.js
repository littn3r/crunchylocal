    const ids=[];
    const pieces=key.split(/(\{\d+\})/).map(part=>{
      const match=/^\{(\d+)\}$/.exec(part);
      if(match){ids.push(match[1]);return '(.*?)';}
      return part.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
    });
